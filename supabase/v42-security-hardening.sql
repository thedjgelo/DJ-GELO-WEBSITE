-- DJ GELO v42 security hardening
-- Run once after the v41 upgrade.

create table if not exists public.inquiry_rate_limits (
  id bigint generated by default as identity primary key,
  fingerprint text not null,
  attempted_at timestamptz not null default now()
);

create index if not exists inquiry_rate_limits_fingerprint_time_idx
  on public.inquiry_rate_limits (fingerprint, attempted_at desc);

alter table public.inquiry_rate_limits enable row level security;

-- No browser role receives direct access. Edge Functions use the service role.
revoke all on public.inquiry_rate_limits from anon, authenticated;
grant all on public.inquiry_rate_limits to service_role;

-- Keep old rate-limit rows from growing forever. Called opportunistically by the function.
create or replace function public.cleanup_inquiry_rate_limits()
returns void
language sql
security definer
set search_path = public
as $$
  delete from public.inquiry_rate_limits
  where attempted_at < now() - interval '2 days';
$$;

revoke all on function public.cleanup_inquiry_rate_limits() from public, anon, authenticated;
grant execute on function public.cleanup_inquiry_rate_limits() to service_role;
